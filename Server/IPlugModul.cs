using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using X13.Repository;

namespace X13 {
  /// <summary>Подсистема, которой управляет сервер: загружается через MEF и вызывается Program в потоке движка.</summary>
  /// <remarks>Init и Start выполняются в порядке возрастания приоритета, а Stop — в порядке убывания;
  /// все методы вызываются в потоке движка. Поэтому плагин может рассчитывать, что каждый плагин
  /// с меньшим приоритетом уже запущен.
  /// <para>Наиболее легко ошибиться в части контракта, описывающей поведение после сбоя.
  /// Init и Start могут выбрасывать исключения: сервер записывает ошибку в журнал, прекращает запуск,
  /// а затем останавливает всё, до чего успел дойти, включая плагин, только что выбросивший исключение,
  /// поскольку Stop является единственным способом завершения в этом интерфейсе. Поэтому Stop может
  /// получить частично созданный объект и не должен предполагать, какую часть Init успел выполнить.
  /// Именно поэтому Repo.Stop защищён флагом _loaded; этот флаг появился после реального такого случая.</para>
  /// <para>Обратная ситуация невозможна: Stop не вызывается для отключённого плагина или плагина,
  /// очередь которого ещё не наступила. Поэтому от состояния «Stop до Init» защищаться не требуется.
  /// Stop также может выбросить исключение. Оно перехватывается и записывается в журнал вместе с достигнутым
  /// состоянием плагина, после чего остальные плагины всё равно останавливаются. Однако плагин, выбросивший
  /// исключение здесь, продолжает удерживать захваченные ресурсы, поэтому небрежность в Stop особенно опасна.</para>
  /// <para>Метод Dispose намеренно отсутствует в этом интерфейсе. При уничтожении контейнера MEF освобождает
  /// все части, реализующие IDisposable; это происходит после Stop. Добавление второго метода завершения
  /// разделило бы одну ответственность между двумя методами без правила, определяющего, какой ресурс где
  /// освобождается.</para></remarks>
  public interface IPlugModul {
    void Init();
    void Start();
    void Tick();
    void Stop();
    /// <summary>Собственный узел плагина внутри /$YS, являющийся корнем всей его конфигурации.</summary>
    Topic Owner { get; }
    /// <summary>Определяет по <see cref="Owner"/>, должен ли сервер вообще запускать этот плагин.</summary>
    bool enabled { get; }
  }
  public interface IPlugModulData {
    int priority { get; }
    string name { get; }
  }
}
